export type KitFile = { name: string; content: string; executable: boolean };

type Method = FinetuneKitRequest["method"];

const METHOD_LABEL: Record<Method, string> = {
  sft_lora: "supervised fine-tuning (SFT) with LoRA",
  sft_qlora: "supervised fine-tuning (SFT) with QLoRA (4-bit base model)",
  dpo_lora: "preference tuning (DPO) with LoRA",
};
const SHORT_LABEL: Record<Method, string> = { sft_lora: "SFT LoRA", sft_qlora: "SFT QLoRA", dpo_lora: "DPO LoRA" };

/** vLLM only accepts these values for --max-lora-rank. */
const VLLM_LORA_RANKS = [8, 16, 32, 64, 128, 256, 320, 512];

/** Python literal for a validated number (JSON numbers such as 1e-7 are valid Python). */
const num = (value: number) => JSON.stringify(value);
/**
 * YAML literal for a number. PyYAML (which Axolotl uses) follows YAML 1.1 and reads "1e-7" as a
 * string, so exponent forms get a decimal point: "1.0e-7".
 */
export const yamlNum = (value: number) => JSON.stringify(value).replace(/^(-?\d+)(e)/i, "$1.0$2");
/** Python string literal; inputs are validated by regex in the contract, JSON quoting is still applied. */
const pyStr = (value: string) => JSON.stringify(value);

function hasData(input: KitTemplateInput, name: string): boolean {
  const file = input.dataFiles.find((entry) => entry.name === name);
  return !!file && file.bytes > 0 && file.records !== 0;
}

function records(input: KitTemplateInput, name: string): string {
  const file = input.dataFiles.find((entry) => entry.name === name);
  if (!file) return "not included";
  if (file.records === null) return `${file.bytes} bytes`;
  return file.records === 1 ? "1 record" : `${file.records} records`;
}

export function vllmMaxLoraRank(rank: number): number {
  return VLLM_LORA_RANKS.find((value) => value >= rank) ?? rank;
}

/** A first guess at the vLLM tool-call parser for a model family; the operator can override it. */
export function guessToolCallParser(baseModel: string): string {
  const name = baseModel.toLowerCase();
  if (name.includes("qwen3-coder")) return "qwen3_coder";
  if (name.includes("llama")) return "llama3_json";
  if (name.includes("mistral") || name.includes("devstral") || name.includes("codestral")) return "mistral";
  if (name.includes("gpt-oss")) return "openai";
  return "hermes";
}

/** Parameter count in billions read from a model name such as "Qwen3-8B" or "llama-3.1-70b-instruct". */
export function parameterBillions(baseModel: string): number | null {
  const match = /(?:^|[^a-z0-9.])(\d+(?:\.\d+)?)b(?![a-z0-9])/i.exec(baseModel);
  const value = match ? Number(match[1]) : NaN;
  return Number.isFinite(value) && value > 0 && value < 2000 ? value : null;
}

/** Rough training memory for one GPU, in GB, at a few thousand tokens per example. */
export function estimateGpuMemoryGb(method: Method, billions: number): number {
  const bytesPerParameter = method === "sft_qlora" ? 0.6 : 2;
  const overhead = method === "dpo_lora" ? 1.4 : 1.3;
  return Math.ceil(billions * bytesPerParameter * overhead + 4);
}

const capitalize = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);

