function prepareDpoPy(input: KitTemplateInput): string {
  return String.raw`#!/usr/bin/env python3
"""Reshape data/dpo.jsonl for Axolotl's chat_template.default DPO loader.

` + provenance(input) + String.raw`

Tatvam writes each pair as {"prompt": [messages], "chosen": [messages], "rejected": [messages]}.
Axolotl expects {"messages": [messages], "chosen": {message}, "rejected": {message}} and keeps only the
role and content of each message.

The compared replies are plain text and carry over unchanged. Tool calls and tool results earlier in
the conversation cannot be expressed as role and content, so by default they are written out as
plain text ("[tool call] read_file(...)", "[tool result] ..."). The model then sees tool activity in a
different format from the one it is served with, which weakens the lesson for tool-heavy conversations;
the TRL kit keeps the native format. Set FLATTEN_TOOL_MESSAGES=0 to skip those pairs instead.
"""

import json
import os
import sys

SOURCE = "data/dpo.jsonl"
TARGET = "data/dpo_axolotl.jsonl"
FLATTEN_TOOL_MESSAGES = os.environ.get("FLATTEN_TOOL_MESSAGES", "1").strip().lower() in ("1", "true", "yes")


def text_of(message):
    content = message.get("content")
    return content if isinstance(content, str) else ""


def plain(message):
    """A role/content message, or None when it cannot be expressed as one."""
    role = message.get("role")
    calls = message.get("tool_calls") or []
    if role in ("system", "user", "assistant") and not calls:
        return {"role": role, "content": text_of(message)}
    if not FLATTEN_TOOL_MESSAGES:
        return None
    if role == "assistant":
        lines = [text_of(message)] if text_of(message) else []
        for call in calls:
            function = call.get("function") or {}
            lines.append(f"[tool call] {function.get('name', '')}({function.get('arguments') or ''})")
        return {"role": "assistant", "content": "\n".join(lines)}
    if role == "tool":
        return {"role": "user", "content": "[tool result]\n" + text_of(message)}
    return None


def merge_consecutive(messages):
    """Join neighbouring messages with the same role; many chat templates require alternating turns."""
    merged = []
    for message in messages:
        if merged and merged[-1]["role"] == message["role"] and message["role"] != "system":
            merged[-1] = {"role": message["role"], "content": merged[-1]["content"] + "\n\n" + message["content"]}
        else:
            merged.append(dict(message))
    return merged


def reshape(record):
    prompt = [plain(message) for message in record.get("prompt") or []]
    if not prompt or any(message is None for message in prompt):
        return None
    sides = {}
    for side in ("chosen", "rejected"):
        messages = record.get(side) or []
        if len(messages) != 1 or messages[0].get("role") != "assistant" or messages[0].get("tool_calls"):
            return None
        if not text_of(messages[0]).strip():
            return None
        sides[side] = {"role": "assistant", "content": text_of(messages[0])}
    return {"messages": merge_consecutive(prompt), "chosen": sides["chosen"], "rejected": sides["rejected"]}


def main():
    kept = skipped = 0
    with open(SOURCE, encoding="utf-8") as source, open(TARGET, "w", encoding="utf-8") as target:
        for line in source:
            if not line.strip():
                continue
            pair = reshape(json.loads(line))
            if pair is None:
                skipped += 1
                continue
            target.write(json.dumps(pair, ensure_ascii=False) + "\n")
            kept += 1
    print(f"Wrote {kept} pairs to {TARGET}; skipped {skipped} that Axolotl's DPO loader cannot express.")
    if kept == 0:
        sys.exit("No pairs left for Axolotl. Generate the kit with the TRL framework instead.")


if __name__ == "__main__":
    main()
`;
}

