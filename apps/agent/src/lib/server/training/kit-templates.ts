function mergeLoraPy(input: KitTemplateInput): string {
  const { request } = input;
  return `#!/usr/bin/env python3
"""Merge the trained LoRA adapter into the base model and save a standalone model for serving.

${provenance(input)}

    python merge_lora.py

Reads output/<OUTPUT_NAME> and writes merged/<OUTPUT_NAME>. The base model is loaded in bfloat16, never
4-bit (even for QLoRA kits), because merging into quantized weights loses accuracy. Expect to need about
2 GB of memory per billion parameters (RAM by default, or GPU memory with MERGE_DEVICE=auto).
"""

import os

import torch
from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer


${PY_SETTING_HELPER}


BASE_MODEL = setting("BASE_MODEL", ${pyStr(request.baseModel)})  # the model the adapter was trained on
OUTPUT_NAME = setting("OUTPUT_NAME", ${pyStr(request.outputName)})
ADAPTER_DIR = setting("ADAPTER_DIR", os.path.join("output", OUTPUT_NAME))
MERGED_DIR = setting("MERGED_DIR", os.path.join("merged", OUTPUT_NAME))
MERGE_DEVICE = setting("MERGE_DEVICE", "cpu")  # "auto" merges on the GPU(s): faster, needs the memory


def main():
    if not os.path.isfile(os.path.join(ADAPTER_DIR, "adapter_config.json")):
        raise SystemExit(f"No adapter found in {ADAPTER_DIR}. Run bash run.sh first.")
    print(f"Loading {BASE_MODEL} in bfloat16 on {MERGE_DEVICE} ...")
    base = AutoModelForCausalLM.from_pretrained(BASE_MODEL, dtype=torch.bfloat16, device_map=MERGE_DEVICE)
    model = PeftModel.from_pretrained(base, ADAPTER_DIR)
    print("Merging the adapter into the base weights ...")
    merged = model.merge_and_unload()
    merged.save_pretrained(MERGED_DIR, safe_serialization=True, max_shard_size="5GB")
    # Keep the tokenizer (and its chat template) next to the weights so vLLM renders prompts the same way.
    has_tokenizer = os.path.isfile(os.path.join(ADAPTER_DIR, "tokenizer_config.json"))
    AutoTokenizer.from_pretrained(ADAPTER_DIR if has_tokenizer else BASE_MODEL).save_pretrained(MERGED_DIR)
    print(f"Merged model saved to {MERGED_DIR}. Next: bash serve_vllm.sh merged (see README.md).")


if __name__ == "__main__":
    main()
`;
}

