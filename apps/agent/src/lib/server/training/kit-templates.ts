function trainSftPy(input: KitTemplateInput): string {
  const qlora = input.request.method === "sft_qlora";
  const evalFile = hasData(input, "sft_eval.jsonl") ? pyStr("data/sft_eval.jsonl") : "None  # this export has no held-out split";
  const peftImports = qlora ? "LoraConfig, prepare_model_for_kbit_training" : "LoraConfig";
  const transformersImports = qlora
    ? "AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig"
    : "AutoModelForCausalLM, AutoTokenizer";
  return `#!/usr/bin/env python3
"""Fine-tune ${input.request.baseModel} on a Tatvam dataset: ${METHOD_LABEL[input.request.method]}, using Hugging Face TRL.

${provenance(input)}

What it does:
  1. Loads data/sft_train.jsonl (and data/sft_eval.jsonl when present) with datasets.load_dataset("json").
  2. Renders each conversation, tool calls and tool results included, with the base model's own chat
     template, and computes the loss only on the assistant's turns (replies and tool calls).
  3. Trains a LoRA adapter${qlora ? " on the base model loaded in 4-bit (QLoRA)" : ""} and saves it to output/<OUTPUT_NAME>.

Every setting below can be overridden with an environment variable of the same name, for example:

    EPOCHS=1 LEARNING_RATE=1e-4 python train.py
"""

import json
import os

import torch
from datasets import load_dataset
from peft import ${peftImports}
from transformers import ${transformersImports}
from trl import SFTConfig, SFTTrainer


${PY_SETTING_HELPER}


${pyCommonSettings(input)}
WARMUP_RATIO = setting("WARMUP_RATIO", 0.03, float)  # share of steps spent ramping up the learning rate

# ── Data ──────────────────────────────────────────────────────────────────────────────────────
TRAIN_FILE = "data/sft_train.jsonl"
EVAL_FILE = ${evalFile}
# Learn only from assistant turns. Off means every token counts, tool output and user text included.
ASSISTANT_ONLY_LOSS = setting("ASSISTANT_ONLY_LOSS", True, flag)
# Text that ends an assistant turn in the rendered conversation. Empty means the tokenizer's EOS token.
END_OF_TURN = setting("END_OF_TURN", "")


${PY_DATA_HELPERS}


def assistant_spans(tokenizer, messages, tools, text):
    """Character ranges of the assistant turns inside the rendered text, or None when they cannot be found."""
    end_of_turn = END_OF_TURN or tokenizer.eos_token or ""
    spans = []
    for index, message in enumerate(messages):
        if message.get("role") != "assistant" or index == 0:
            continue
        before = render(tokenizer, messages[:index], tools, add_generation_prompt=True)
        if not text.startswith(before):
            return None  # this template rewrites earlier turns; train on the whole example instead
        start = len(before)
        through = render(tokenizer, messages[: index + 1], tools)
        if text.startswith(through):
            end = len(through)
        else:
            # Some templates (Qwen3, for example) render the last assistant turn differently from earlier
            # ones, so end this turn at its end-of-turn marker instead.
            stop = text.find(end_of_turn, start) if end_of_turn else -1
            end = len(text) if stop < 0 else stop + len(end_of_turn)
        spans.append((start, end))
    return spans


def mask_from_spans(offsets, spans):
    """1 for tokens that start inside an assistant span, 0 for everything else."""
    mask, current = [], 0
    for token_start, _ in offsets:
        while current < len(spans) and token_start >= spans[current][1]:
            current += 1
        inside = current < len(spans) and spans[current][0] <= token_start
        mask.append(1 if inside else 0)
    return mask


def tokenize_example(example, tokenizer):
    record = record_of(example)
    messages = normalize_messages(record["messages"])
    tools = record.get("tools") or None
    text = render(tokenizer, messages, tools)
    spans = assistant_spans(tokenizer, messages, tools, text) if ASSISTANT_ONLY_LOSS else None
    # The chat template already adds any BOS token the model needs.
    encoded = tokenizer(text, add_special_tokens=False, return_offsets_mapping=True)
    input_ids = encoded["input_ids"]
    mask = [1] * len(input_ids) if spans is None else mask_from_spans(encoded["offset_mapping"], spans)
    return {
        "input_ids": input_ids[:MAX_SEQ_LENGTH],
        "completion_mask": mask[:MAX_SEQ_LENGTH],  # TRL computes the loss only where this is 1
        "truncated": len(input_ids) > MAX_SEQ_LENGTH,
        "whole_example": spans is None,
    }


def prepare(path, tokenizer, split):
    raw = load_jsonl(path)
    tokenized = raw.map(
        tokenize_example,
        fn_kwargs={"tokenizer": tokenizer},
        remove_columns=raw.column_names,
        num_proc=max(1, min(DATASET_WORKERS, len(raw))),
        desc=f"Tokenizing {split}",
    )
    truncated = sum(1 for value in tokenized["truncated"] if value)
    whole = sum(1 for value in tokenized["whole_example"] if value)
    tokenized = tokenized.filter(lambda row: any(row["completion_mask"]), desc="Dropping examples with nothing to learn")
    print(
        f"{split}: {len(raw)} conversations, {len(tokenized)} kept, "
        f"{truncated} cut to {MAX_SEQ_LENGTH} tokens, {whole} trained on every token"
    )
    return tokenized.remove_columns(["truncated", "whole_example"])


${pyModelLoader(qlora)}


def main():
    torch.manual_seed(SEED)
    tokenizer = load_tokenizer()
    train_dataset = prepare(TRAIN_FILE, tokenizer, "train")
    eval_dataset = prepare(EVAL_FILE, tokenizer, "eval") if EVAL_FILE and os.path.exists(EVAL_FILE) else None
    dtype = compute_dtype()
    model = load_model(dtype)

    lora_config = LoraConfig(
        r=LORA_RANK,
        lora_alpha=LORA_ALPHA,
        lora_dropout=LORA_DROPOUT,
        target_modules="all-linear",  # adapt every linear layer: the best quality for tool use and code
        bias="none",
        task_type="CAUSAL_LM",
    )
    config = SFTConfig(
        output_dir=OUTPUT_DIR,
        num_train_epochs=EPOCHS,
        learning_rate=LEARNING_RATE,
        lr_scheduler_type="cosine",
        warmup_ratio=WARMUP_RATIO,
        per_device_train_batch_size=BATCH_SIZE,
        per_device_eval_batch_size=BATCH_SIZE,
        gradient_accumulation_steps=GRADIENT_ACCUMULATION,
        max_length=MAX_SEQ_LENGTH,
        completion_only_loss=True,  # use the completion_mask built above
        packing=False,
        optim=${qlora ? '"paged_adamw_8bit",  # pages optimizer state to CPU memory under pressure' : '"adamw_torch",'}
        bf16=dtype == torch.bfloat16,
        fp16=dtype == torch.float16,
        gradient_checkpointing=True,  # trades some speed for much less activation memory
        gradient_checkpointing_kwargs={"use_reentrant": False},
        logging_steps=10,
        save_strategy="epoch",
        save_total_limit=2,
        eval_strategy="epoch" if eval_dataset is not None else "no",
        report_to=REPORT_TO,
        seed=SEED,
    )
    trainer = SFTTrainer(
        model=model,
        args=config,
        train_dataset=train_dataset,
        eval_dataset=eval_dataset,
        processing_class=tokenizer,
        peft_config=lora_config,
    )
    trainer.train()
    trainer.save_model(OUTPUT_DIR)  # saves only the adapter (adapter_config.json, adapter_model.safetensors)
    if trainer.is_world_process_zero():
        tokenizer.save_pretrained(OUTPUT_DIR)
        print(f"Saved the LoRA adapter to {OUTPUT_DIR}. Next: python merge_lora.py (see README.md).")


if __name__ == "__main__":
    main()
`;
}

