/** Every generated file for a kit (the dataset copies under data/ are added by kits.ts). */
export function renderKit(input: KitTemplateInput): KitFile[] {
  const { method, framework } = input.request;
  const files: KitFile[] = [
    { name: "README.md", content: readme(input), executable: false },
    { name: "requirements.txt", content: requirementsTxt(input), executable: false },
  ];
  if (framework === "trl")
    files.push({ name: "train.py", content: method === "dpo_lora" ? trainDpoPy(input) : trainSftPy(input), executable: true });
  else {
    files.push({ name: "axolotl.yaml", content: axolotlYaml(input), executable: false });
    if (method === "dpo_lora") files.push({ name: "prepare_dpo.py", content: prepareDpoPy(input), executable: true });
  }
  files.push(
    { name: "run.sh", content: runSh(input), executable: true },
    { name: "merge_lora.py", content: mergeLoraPy(input), executable: true },
    { name: "serve_vllm.sh", content: serveVllmSh(input), executable: true },
    { name: "register.json", content: `${JSON.stringify(registerBody(input), null, 2)}\n`, executable: false },
  );
  return files;
}
